import { randomUUID } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const executable = fileURLToPath(new URL('./cli.js', import.meta.url));
const extensions = {
  pi: fileURLToPath(new URL('../integrations/pi.ts', import.meta.url)),
  opencode: fileURLToPath(new URL('../integrations/opencode.mjs', import.meta.url)),
};
const marker = '// Generated by Focus Code.\n';
const claudeSkillMarker = '<!-- Generated by Focus Code. -->';
const claudeSkillPath = 'skills/focus-code/SKILL.md';
const claudeProfile = () => resolve(process.env.CLAUDE_CONFIG_DIR || join(homedir(), '.claude'));
const quote = value => `'${value.replaceAll("'", "'\\''")}'`;
const matchers = {
  claude: '^(Bash|PowerShell|Edit|Write|MultiEdit|NotebookEdit)$',
  codex: '^(Bash|apply_patch)$',
  gemini: '^(run_shell_command|replace|write_file|apply_patch|edit_file)$',
  trae: '^(RunCommand|Write|Edit)$',
  'trae-cli': '^(Bash|RunCommand|exec_command|Edit|Write|apply_patch)$',
};
export const agents = ['claude', 'codex', 'pi', 'opencode', 'gemini', 'trae'];
export const globalAgents = new Set(['claude', 'codex', 'opencode', 'gemini', 'trae', 'pi']);

export function writeConfig(file, contents, mode) {
  const temporary = `${file}.focus-${randomUUID()}`;
  try {
    writeFileSync(temporary, contents, { mode, flag: 'wx' });
    renameSync(temporary, file);
  } finally {
    rmSync(temporary, { force: true });
  }
}

function installClaudeSkill(directory, { global = false } = {}) {
  const file = join(directory, claudeSkillPath);
  if (!global) {
    let parent = directory;
    for (const part of ['skills', 'focus-code']) {
      parent = join(parent, part);
      mkdirSync(parent, { recursive: true });
      if (realpathSync(parent) !== parent) throw new Error(`配置目录不能是符号链接 ${parent}`);
    }
  }
  const contents = `---
name: focus-code
description: 在浏览器中查看当前 Git 工程的 Focus Code 变动记录。
argument-hint: show
disable-model-invocation: true
---

${claudeSkillMarker}

The local Focus Code hook handles this command. If this text reaches Claude, the hook did not handle the invocation. Tell the user to reinstall the Focus Code Claude Code integration and restart the client. Do not call tools or modify files.
`;
  writeFocusSkill(file, contents);
}

function writeFocusSkill(file, contents, generated = claudeSkillMarker) {
  try {
    const stat = lstatSync(file);
    if (!stat.isFile()) throw new Error(`Focus Code 指令路径应是普通文件 ${file}`);
    const existing = readFileSync(file, 'utf8');
    if (existing === contents) return;
    if (!existing.includes(generated)) throw new Error(`已存在自定义的 Focus Code 指令配置 ${file}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
  writeConfig(file, contents, 0o600);
}

export function codexSkillPath() {
  return join(homedir(), '.agents', claudeSkillPath);
}

function installCodexSkill() {
  const file = codexSkillPath();
  writeFocusSkill(file, `---
name: focus-code
description: Open the local Focus Code timeline for the current Git project on explicit request.
---

${claudeSkillMarker}

The Focus Code hook handles the explicit command \`$focus-code show\`. If this text reaches Codex, ask the user to paste that command as its own message and verify Focus Code hooks are enabled in \`/hooks\`. Do not run commands or modify files for this skill.
`);
  const generated = '# Generated by Focus Code.';
  writeFocusSkill(join(dirname(file), 'agents', 'openai.yaml'), `${generated}
policy:
  allow_implicit_invocation: false
`, generated);
}

export function hasCodexSkill() {
  try { return readFileSync(codexSkillPath(), 'utf8').includes(claudeSkillMarker); }
  catch { return false; }
}

export function hasClaudeSkill(root) {
  return [claudeProfile(), join(root, '.claude')].some(directory => {
    try { return readFileSync(join(directory, claudeSkillPath), 'utf8').includes(claudeSkillMarker); }
    catch { return false; }
  });
}

export function installGlobal(source) {
  if (source === 'trae') {
    const international = join(homedir(), '.trae');
    const china = join(homedir(), '.trae-cn');
    const profiles = existsSync(china) ? [international, china] : [international];
    return profiles.map(directory => {
      mkdirSync(directory, { recursive: true, mode: 0o700 });
      return installConfig(join(realpathSync(directory), 'hooks.json'), source, { followSymlink: true, mode: 0o600 });
    }).join('\n');
  }
  const directory = {
    claude: claudeProfile(),
    codex: process.env.CODEX_HOME || join(homedir(), '.codex'),
    opencode: process.env.OPENCODE_CONFIG_DIR || join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'opencode'),
    gemini: join(process.env.GEMINI_CLI_HOME || homedir(), '.gemini'),
    pi: process.env.PI_CODING_AGENT_DIR || join(homedir(), '.pi', 'agent'),
  }[source];
  const locations = { codex: 'hooks.json', opencode: 'plugins/focus-code.js', pi: 'extensions/focus-code.ts' };
  const file = resolve(directory, locations[source] ?? 'settings.json');
  const configDir = dirname(file);
  mkdirSync(configDir, { recursive: true, mode: 0o700 });
  if (source === 'claude') installClaudeSkill(configDir, { global: true });
  if (source === 'codex') installCodexSkill();
  return installConfig(join(realpathSync(configDir), basename(file)), source, {
    followSymlink: !Object.hasOwn(extensions, source), mode: 0o600,
  });
}

export function install(root, source) {
  if (!agents.includes(source)) throw new Error(`支持的集成为 ${agents.join('、')}。`);
  const relativePath = {
    claude: '.claude/settings.local.json', codex: '.codex/hooks.json', pi: '.pi/extensions/focus-code.ts',
    opencode: '.opencode/plugins/focus-code.js', gemini: '.gemini/settings.json', trae: '.trae/hooks.json',
  }[source];
  const file = join(root, relativePath);
  const parts = relativePath.split('/').slice(0, -1);
  let parent = root;
  for (const part of parts) {
    parent = join(parent, part);
    mkdirSync(parent, { recursive: true });
    if (realpathSync(parent) !== parent) throw new Error(`配置目录不能是符号链接 ${parent}`);
  }
  if (source === 'claude') installClaudeSkill(parent);
  return installConfig(file, source);
}

function installConfig(file, source, { followSymlink = false, mode = 0o644 } = {}) {
  const configuredPath = file;
  let original;
  try {
    let stat = lstatSync(file);
    if (followSymlink && stat.isSymbolicLink()) {
      try { file = realpathSync(file); }
      catch (error) { throw new Error(`无法解析用户设置的符号链接 ${file}`, { cause: error }); }
      stat = lstatSync(file);
    }
    if (!stat.isFile()) throw new Error(`配置路径应是普通文件 ${file}`);
    original = readFileSync(file, 'utf8');
    mode = stat.mode & 0o777;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (Object.hasOwn(extensions, source)) {
    const extension = JSON.stringify(extensions[source]);
    const entry = source === 'pi' ? `export { default } from ${extension};\n`
      : `import { createOpenCodePlugin } from ${extension};\nexport const FocusCode = input => createOpenCodePlugin(input, ${JSON.stringify(process.execPath)});\n`;
    const content = marker + entry;
    if (original === content) return file;
    if (original !== undefined && !original.startsWith(marker)) throw new Error(`扩展文件已存在 ${file}`);
    writeConfig(file, content, mode);
    return file;
  }
  const config = JSON.parse(original ?? '{}');
  config.hooks ??= {};
  if (source === 'trae') config.version ??= 1;
  for (const [event, entry] of Object.entries(hookGroups(source))) {
    const command = entry.hooks[0].command;
    const existing = config.hooks[event] ?? [];
    const group = existing.find(item => item.matcher === entry.matcher && item.hooks?.some(hook => hook.command === command));
    if (group) group.hooks.find(hook => hook.command === command).timeout = entry.hooks[0].timeout;
    else config.hooks[event] = [...existing, entry];
  }
  const contents = `${JSON.stringify(config, null, 2)}\n`;
  if (contents !== original) writeConfig(file, contents, mode);
  return configuredPath;
}

export function hookGroups(source) {
  const command = `${quote(process.execPath)} --disable-warning=ExperimentalWarning ${quote(executable)} hook ${source}`;
  const matcher = matchers[source];
  const events = source === 'gemini'
    ? { BeforeAgent: null, BeforeTool: matcher, AfterTool: matcher, AfterAgent: null, SessionEnd: null }
    : { UserPromptSubmit: null, PreToolUse: matcher, PostToolUse: matcher, Stop: null };
  if (source === 'claude') {
    events.UserPromptExpansion = '^focus-code$';
    events.PostToolUseFailure = matcher;
    events.PermissionDenied = matcher;
    events.SessionEnd = null;
  } else if (source === 'codex') {
    events.Interrupt = null;
    events.SessionEnd = null;
  }
  return Object.fromEntries(Object.entries(events).map(([event, pattern]) => {
    const timeout = source === 'gemini' ? 15000 : source === 'codex' && ['Interrupt', 'SessionEnd'].includes(event) ? 3 : 15;
    const name = source === 'gemini' ? `focus-code-${event}` : undefined;
    return [event, { ...(pattern ? { matcher: pattern } : {}), hooks: [{ type: 'command', ...(name ? { name } : {}), command, timeout }] }];
  }));
}
